// Derive a continuous drape from each native skirt, preserving its dimensions.
// The convex fabric envelope bridges the leg gap; actual limbs never move.
const fs = require("node:fs");
const { chromium } = require(
  process.env.PLAYWRIGHT_MODULE || "playwright-core",
);
(async () => {
  const b = await chromium.launch({
    executablePath: process.env.CHROMIUM_PATH || "/usr/bin/chromium",
    args: ["--no-sandbox"],
  });
  try {
    const page = await b.newPage();
    await page.goto(process.env.APP_URL || "http://127.0.0.1:4178");
    const paths = await page.evaluate(() => {
      const out = {};
      const cross = (o, a, b) =>
        (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0]);
      const hull = (pts) => {
        pts.sort((a, b) => a[0] - b[0] || a[1] - b[1]);
        const l = [],
          u = [];
        for (const p of pts) {
          while (l.length >= 2 && cross(l.at(-2), l.at(-1), p) <= 0) l.pop();
          l.push(p);
        }
        for (const p of pts.toReversed()) {
          while (u.length >= 2 && cross(u.at(-2), u.at(-1), p) <= 0) u.pop();
          u.push(p);
        }
        return l.slice(0, -1).concat(u.slice(0, -1));
      };
      for (const { alias: pose } of D.lessonPoses) {
        const svg = document.createElementNS(
          "http://www.w3.org/2000/svg",
          "svg",
        );
        svg.innerHTML = garmentPaths(
          `assets/images/result/${pose}/`,
          "chima",
          "bottom",
        );
        document.body.append(svg);
        const pts = [];
        for (const path of svg.querySelectorAll("path")) {
          const len = path.getTotalLength();
          for (let t = 0; t < len; t += 2) {
            const p = path.getPointAtLength(t);
            pts.push([p.x, p.y]);
          }
        }
        svg.remove();
        const bx = GARMENT_LAYOUT[pose].skirt;
        if (
          /^(reading_writing|crafting|eating_drinking)_/.test(pose) ||
          [
            "playing_music_01",
            "playing_music_05",
            "dancing_hansam_03",
          ].includes(pose)
        ) {
          pts.push(
            [bx.x - 10, bx.y + bx.h - 7],
            [bx.x + bx.w + 10, bx.y + bx.h - 7],
          );
        }
        let h = hull(pts);
        if (
          [
            "holding_fan_01",
            "holding_fan_03",
            "trudging_01",
            "trudging_03",
            "dancing_05",
            "posing_01",
            "with_child_02",
          ].includes(pose)
        )
          h = h.map(([x, y]) => [
            x +
              ((x < bx.x + bx.w / 2 ? -1 : 1) *
                18 *
                Math.max(0, (y - bx.y) / bx.h - 0.4)) /
                0.6,
            y,
          ]);
        const q = (p) => p.map((v) => Number(v.toFixed(2))).join(" ");
        const lerp = (a, b, t) => [
          a[0] * (1 - t) + b[0] * t,
          a[1] * (1 - t) + b[1] * t,
        ];
        const rounded = h.map((p, i) => {
          const prev = h[(i + h.length - 1) % h.length],
            next = h[(i + 1) % h.length];
          return {
            p,
            a: lerp(
              p,
              prev,
              Math.min(0.3, 5 / Math.hypot(prev[0] - p[0], prev[1] - p[1])),
            ),
            b: lerp(
              p,
              next,
              Math.min(0.3, 5 / Math.hypot(next[0] - p[0], next[1] - p[1])),
            ),
          };
        });
        out[pose] =
          "M" +
          q(rounded[0].a) +
          rounded
            .map(
              ({ p, a, b }, i) =>
                (i ? "L" + q(a) : "") + "Q" + q(p) + " " + q(b),
            )
            .join("") +
          "Z";
      }
      return out;
    });
    fs.writeFileSync(
      "js/art/garment-skirts.js",
      '"use strict";\n\n// Generated by scripts/build-skirt-contours.cjs; limbs retain their native coordinates.\nconst GARMENT_SKIRTS = ' +
        JSON.stringify(paths, null, 2) +
        ';\n\nfunction skirtContour(pose, base) {\n  return GARMENT_SKIRTS[pose] ? `<path d="${GARMENT_SKIRTS[pose]}"/>` : garmentPaths(base,"chima","bottom");\n}\n',
    );
    console.log(
      `Generated ${Object.keys(paths).length} continuous skirt contours.`,
    );
  } finally {
    await b.close();
  }
})().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
