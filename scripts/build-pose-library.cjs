/* Rebuild runtime modules for reviewed poses whose uploaded result layers exist. */
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const { chromium } = require(
  process.env.PLAYWRIGHT_MODULE || "playwright-core",
);
const deriveAnatomy = require("./pose-anatomy.cjs");
const root = path.resolve(__dirname, "..");
const library = "art-library/pungsokdo/";
const selection = JSON.parse(
  fs.readFileSync(path.join(root, library, "selection.json")),
);
const context = { window: {} };
vm.runInNewContext(
  fs.readFileSync(path.join(root, "catalog.js"), "utf8"),
  context,
);
const existing = new Set(
  context.window.CATALOG.lessonPoses.map((p) => p.alias),
);
const resultRoot = path.join(root, library, "assets/images/result");
const poses = Object.keys(selection.includedPoses).filter(
  (alias) =>
    !existing.has(alias) && fs.existsSync(path.join(resultRoot, alias)),
);

const headgear = {
  cheering_04: { angle: -8 },
  dancing_01: { angle: -8 },
  dancing_02: { angle: 12 },
  dancing_03: { angle: -40 },
  dancing_04: { angle: 165, headX: 190, headY: 299 },
  dancing_05: { angle: 8 },
  posing_01: { angle: -8 },
  posing_02: { angle: -8 },
  posing_03: { angle: 16 },
  working_out_01: { angle: 12 },
  working_out_02: { angle: 16 },
  working_out_03: { angle: 16 },
};

function sources(alias) {
  const manifest = JSON.parse(
    fs.readFileSync(
      path.join(root, library, "manifests/result", alias + ".json"),
    ),
  );
  return Object.fromEntries(
    manifest.map(({ path: file }) => {
      const source = library + file;
      const value = file.endsWith(".svg")
        ? fs.readFileSync(path.join(root, source), "utf8")
        : source;
      return [file, value];
    }),
  );
}

(async () => {
  const browser = await chromium.launch({
    executablePath: process.env.CHROMIUM_PATH || "/usr/bin/chromium",
    args: ["--no-sandbox"],
  });
  try {
    const page = await browser.newPage();
    const inputs = poses.map((pose) => {
      const entries = Object.entries(sources(pose)).filter(
        ([name]) =>
          name.includes("/clothes/") ||
          /\/(?:skintones\/face_overlay@2x.png|hairs\/short_hair_(?:fill.svg|overlay@2x.png))$/.test(
            name,
          ),
      );
      return {
        pose,
        files: Object.fromEntries(
          entries.map(([name, value]) => {
            const local = name.split("/" + pose + "/")[1];
            const buffer = name.endsWith(".svg")
              ? Buffer.from(value.replace(/var\(--[a-z-]+\)/g, "#202020"))
              : fs.readFileSync(path.join(root, value));
            return [
              local,
              `data:image/${name.endsWith(".svg") ? "svg+xml" : "png"};base64,${buffer.toString("base64")}`,
            ];
          }),
        ),
      };
    });
    const anatomy = await page.evaluate(deriveAnatomy, inputs);
    for (const pose of poses) {
      const { base, face, layout } = anatomy[pose];
      const assets = sources(pose);
      assets[`assets/images/options/poses/${pose}@2x.png`] =
        `${library}assets/images/poses/thumbs/${pose}@2x.png`;
      const body =
        [
          "// Generated by scripts/build-pose-library.cjs. Native image files are unchanged.",
          `Object.assign(window.ASSET_DATA, ${JSON.stringify(assets, null, 2)});`,
          `window.CATALOG.skinVectors[${JSON.stringify(pose)}] = ${JSON.stringify({ base, face })};`,
          `window.ART_LAYOUT[${JSON.stringify(pose)}] = ${JSON.stringify({ ...layout, ...headgear[pose] })};`,
        ].join("\n") + "\n";
      fs.mkdirSync(path.join(root, "assets/poses"), { recursive: true });
      fs.writeFileSync(path.join(root, "assets/poses", pose + ".js"), body);
    }
    const records = poses.map((alias) => ({
      alias,
      label: selection.includedPoses[alias],
    }));
    fs.writeFileSync(
      path.join(root, "js/data/pose-library.js"),
      '"use strict";\n\n// Reviewed poses with complete rendering modules.\n' +
        `window.LIBRARY_POSES = ${JSON.stringify(records, null, 2)};\n` +
        "window.CATALOG.lessonPoses.push(...window.LIBRARY_POSES);\n",
    );
    console.log(`Generated ${poses.length} runtime pose modules.`);
  } finally {
    await browser.close();
  }
})().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
