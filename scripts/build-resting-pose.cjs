// Build a reclining pose from the uploaded source. The separate floor device
// is excluded from every clothing overlay; the figure and its limbs are intact.
const fs = require("node:fs");
const path = require("node:path");
const { chromium } = require(
  process.env.PLAYWRIGHT_MODULE || "playwright-core",
);
const deriveAnatomy = require("./pose-anatomy.cjs");
const root = path.resolve(__dirname, "..");
const source = process.argv[2];
if (!source)
  throw Error("Usage: node scripts/build-resting-pose.cjs <source directory>");
const alias = "resting_02",
  original = "lying_02";
const assets = {},
  files = {};
for (const line of fs
  .readFileSync(path.join(source, "images.jsonl"), "utf8")
  .trim()
  .split("\n")) {
  const row = JSON.parse(line),
    url = new URL(row.url);
  if (
    !url.pathname.includes(`/result/${original}/`) ||
    url.pathname.includes("jjimjilbang")
  )
    continue;
  const local = url.pathname.split(`/${original}/`)[1];
  let buffer = fs.readFileSync(path.join(source, row.file)),
    value;
  if (row.file.endsWith(".svg")) value = buffer.toString();
  else {
    value = `data:image/png;base64,${buffer.toString("base64")}`;
    if (local.startsWith("clothes/")) {
      const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="360" height="360" viewBox="0 0 360 360"><defs><clipPath id="figure"><path clip-rule="evenodd" d="M0 0H360V360H0Z M225 243V276H279V243Z"/></clipPath></defs><image href="${value}" width="360" height="360" clip-path="url(#figure)"/></svg>`;
      value = `data:image/svg+xml;base64,${Buffer.from(svg).toString("base64")}`;
    }
  }
  assets[`assets/images/result/${alias}/${local}`] = value;
  if (
    local.startsWith("clothes/") ||
    /^(skintones\/face_overlay|hairs\/short_hair_)/.test(local)
  )
    files[local] = local.endsWith(".svg")
      ? "data:image/svg+xml;base64," +
        Buffer.from(value.replace(/var\(--[a-z-]+\)/g, "#202020")).toString(
          "base64",
        )
      : value;
}
(async () => {
  const browser = await chromium.launch({
    executablePath: process.env.CHROMIUM_PATH || "/usr/bin/chromium",
    args: ["--no-sandbox"],
  });
  try {
    const page = await browser.newPage();
    const result = await page.evaluate(deriveAnatomy, [{ pose: alias, files }]);
    const { base, face, layout } = result[alias];
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 360 360"><path fill="#D3B08C" d="${base}"/>${assets[`assets/images/result/${alias}/clothes/baji_fill.svg`].replace(/<\/?svg[^>]*>/g, "").replace(/var\(--[a-z-]+\)/g, "#F4F3EF")}<image href="${assets[`assets/images/result/${alias}/clothes/baji_overlay@2x.png`]}" width="360" height="360"/><path fill="#D3B08C" d="${face}"/><image href="${assets[`assets/images/result/${alias}/skintones/face_overlay@2x.png`]}" width="360" height="360"/></svg>`;
    assets[`assets/images/options/poses/${alias}@2x.png`] =
      "data:image/svg+xml;base64," + Buffer.from(svg).toString("base64");
    fs.writeFileSync(
      path.join(root, "assets/poses", alias + ".js"),
      "// Generated by scripts/build-resting-pose.cjs. Floor device is masked out.\n" +
        `Object.assign(window.ASSET_DATA, ${JSON.stringify(assets)});\nwindow.CATALOG.skinVectors[${JSON.stringify(alias)}] = ${JSON.stringify({ base, face })};\nwindow.ART_LAYOUT[${JSON.stringify(alias)}] = ${JSON.stringify({ ...layout, angle: 18 })};\n`,
    );
    console.log(
      "Generated device-free reclining pose:",
      Object.keys(assets).length,
      "layers",
    );
  } finally {
    await browser.close();
  }
})().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
